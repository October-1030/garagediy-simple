import assert from 'node:assert/strict';
import { initialPlan, makeUnits, fitIssues, moveUnit, estimate, parsePlan } from '../src/lib/planner.ts';
const p = initialPlan();
assert.deepEqual(fitIssues(p), []);
assert.equal(estimate(p.units).total, 1656);
assert.ok(fitIssues({ ...p, width: 97 }).length);
assert.deepEqual(fitIssues({ ...p, width: 98 }), []);
assert.ok(fitIssues({ ...p, width: 120, units: makeUnits('Full wall') }).length);
assert.equal(moveUnit(p, 't1', -1), null);
assert.equal(moveUnit(p, 't1', 1), null);
assert.ok(moveUnit(p, 'w2', 1));
assert.equal(estimate(p.units.filter(u => u.id !== 'b1')).total, 1656 - 275 - 24 - 35);
assert.equal(estimate([]).total, 0);
assert.deepEqual(parsePlan(JSON.stringify(p)), p);
assert.equal(parsePlan('{broken'), null);
assert.equal(parsePlan(JSON.stringify({ ...p, units: [{ id: 'x', kind: '__proto__', x: 0 }] })), null);
assert.equal(parsePlan(JSON.stringify({ ...p, width: 0 })), null);
assert.equal(parsePlan(JSON.stringify({ ...p, units: [p.units[0], p.units[0]] })), null);
console.log('PASS: 14 dimension, collision, pricing and persistence assertions');
